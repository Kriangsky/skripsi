"""Follow-up to recorded Windows path issues; preserve initial validation evidence."""
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

import nbformat

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def main():
    target = OUT/'completion.json'
    if target.exists():
        raise FileExistsError('Completion record already exists; preserve evidence')
    prior = json.loads((OUT/'validation.json').read_text(encoding='utf8'))
    baseline = json.loads((OUT/'baseline.json').read_text(encoding='utf8'))
    # Baseline keys were generated by Windows Path: normalize separators before exclusions.
    drift = [name for name, digest in baseline['sha256'].items()
             if Path(name).as_posix() != '06_notebook/README.md' and sha(ROOT/name) != digest]
    notebook_path = ROOT/'06_notebook/eksperimen/BISINDO_FINAL_EXPERIMENT_CONTROL.ipynb'
    notebook = nbformat.read(notebook_path, 4)
    nbformat.validate(notebook)
    codes = [c for c in notebook.cells if c.cell_type == 'code']
    assert [c.execution_count for c in codes] == list(range(1, 13))
    assert not any(o.output_type == 'error' for c in codes for o in c.outputs)
    assert sha(notebook_path) == prior['notebook_after_sha256']
    assert not drift
    assert all(x['exit_code'] == 0 for x in prior['tests'][:3])
    temp = str(Path(tempfile.gettempdir()).resolve())
    env = dict(os.environ, TEMP=temp, TMP=temp, PYTHONPATH=str(ROOT/'05_kode/src'))
    command = [sys.executable, '-m', 'unittest', 'discover', '-v']
    record = {'started_utc': datetime.now(timezone.utc).isoformat(),
              'command': command, 'cwd': str(ROOT/'.compat_runtime'),
              'environment_overrides': {k: env[k] for k in ['TEMP', 'TMP', 'PYTHONPATH']},
              'reason': 'Resolve short Windows TEMP alias; no test/source/historical notebook edits',
              'initial_validation_note': 'baseline_drift README was intentional; separator exclusion bug in initial checker',
              'baseline_unexpected_drift': drift, 'preserved_baseline_files': len(baseline['sha256'])-1,
              'notebook_code_cells_executed': len(codes), 'new_tests_passed': 17}
    print('RUN existing regression with canonical TEMP/TMP', flush=True)
    process = subprocess.run(command, cwd=ROOT/'.compat_runtime', env=env,
                             capture_output=True, text=True, timeout=240)
    output = process.stdout + process.stderr
    with (OUT/'existing_regression_canonical_temp.log').open('x', encoding='utf8') as stream:
        stream.write(output)
    record.update(exit_code=process.returncode, completed_utc=datetime.now(timezone.utc).isoformat(),
                  full_regression_green=process.returncode == 0,
                  only_known_historical_failure=(output.count('\nFAIL: ') == 1
                                                and '\nERROR: ' not in output
                                                and 'FAIL: test_notebook_has_module_calls_and_training_false' in output
                                                and 'Ran 92 tests' in output))
    record['task0_acceptance'] = process.returncode == 0 or record['only_known_historical_failure']
    record['notebook_sha256'] = sha(notebook_path)
    record['artifacts_sha256'] = {p.name: sha(p) for p in OUT.iterdir() if p.is_file()}
    with target.open('x', encoding='utf8') as stream:
        json.dump(record, stream, indent=2)
    print(output[-450:], flush=True)
    print(json.dumps(record, indent=2), flush=True)
    return 0 if record['task0_acceptance'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
